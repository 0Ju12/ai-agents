FRACTIONS = [(0.25, "¼"), (1 / 3, "⅓"), (0.5, "½"), (2 / 3, "⅔"), (0.75, "¾")]


def nice(x):
    whole = int(x)
    rest = x - whole
    frac = min(FRACTIONS + [(0, ""), (1, "")], key=lambda f: abs(f[0] - rest))
    if frac[0] == 1:
        whole, frac = whole + 1, (0, "")
    text = (str(whole) if whole else "") + frac[1]
    return text or "약간"


def household(name, grams):
    """'간장', 8 → '약 ½큰술' · '두부', 150 → '½모'"""
    if grams is None:
        return ""
    if name in SPOON:
        spoons = grams / SPOON[name]
        if spoons < 0.3:
            return f"약 {nice(spoons * 3)}작은술"
        return f"약 {nice(spoons)}큰술"
    if name in PIECE:
        unit, g = PIECE[name]
        return f"{nice(grams / g)}{unit}" if grams / g >= 0.2 else "조금"
    if name in CUP:
        return f"약 {nice(grams / CUP[name])}컵" if name == "우유" else f"약 {nice(grams / CUP[name])}줌"
    return ""


def amount_text(name, grams):
    h = household(name, grams)
    return f"{grams:g}g" + (f"({h})" if h else "") if grams is not None else "적당량"


