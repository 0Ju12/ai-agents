def enrich(card, names):
    """단계 카드에 익힘 기준·권장 불 세기·고기 안전 안내를 더한다."""
    action = card["동작"]
    tip = DONE.get(action, "")
    if action in ("볶기", "굽기", "끓이기") and (any(m in card["설명"] for m in MEAT) or ("고기" in card["설명"] and any(m in names for m in MEAT))):
        tip += " 고기는 속까지 익어 분홍빛이 없어야 해요."
    if action == "볶기" and "양파" in card["설명"]:
        tip = "양파가 투명해질 때까지 볶아요. " + tip
    card["익힘 기준"] = tip.strip()
    if not card.get("불 세기") and action in HEAT:
        card["불 세기"] = HEAT[action]
        card["불 세기 권장"] = True
    return card


